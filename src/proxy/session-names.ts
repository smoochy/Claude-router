import { readdirSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

/**
 * Resolves a Claude Code session's own display name from its transcript,
 * `~/.claude/projects/<project-dir>/<sessionId>.jsonl` (#4267).
 *
 * The ticket's premise — a transcript-wide "summary" field — does not hold:
 * checked against this machine's live transcripts, none of ~4700 files carry
 * a `summary` field. What the file actually carries are standalone lines
 * `{"type":"ai-title","sessionId":...,"aiTitle":...}` and
 * `{"type":"custom-title","sessionId":...,"customTitle":...}`, present on
 * roughly a quarter of sessions (most sessions are simply never named). A
 * user-set `custom-title` wins over the autogenerated `ai-title`; the last
 * line of either kind wins, since a session can be renamed mid-run.
 *
 * Best-effort only: a missing projects directory, a missing transcript file,
 * or an unparseable line each fall through to `undefined` rather than
 * throwing — callers fall back to the derived label. Nothing but the title
 * string itself ever leaves this module.
 */
function projectsRoot(): string {
  return process.env.CLAUDE_PROJECTS_DIR ?? join(homedir(), '.claude', 'projects');
}

// ponytail: full directory scan per cache miss (the project-dir for a given
// sessionId isn't known up front), cached forever per process since a title
// essentially never changes after it's set. Fine at dashboard scale (tens of
// distinct sessions per render); swap for an indexed lookup if a long-running
// install's project-dir count makes the scan itself slow.
const titleCache = new Map<string, string | undefined>();

export function lookupSessionTitle(sessionId: string, root: string = projectsRoot()): string | undefined {
  const cacheKey = `${root}\u0000${sessionId}`;
  if (titleCache.has(cacheKey)) return titleCache.get(cacheKey);
  const title = findTitle(sessionId, root);
  titleCache.set(cacheKey, title);
  return title;
}

function findTitle(sessionId: string, root: string): string | undefined {
  let dirs: string[];
  try {
    dirs = readdirSync(root);
  } catch {
    return undefined;
  }
  for (const dir of dirs) {
    let text: string;
    try {
      text = readFileSync(join(root, dir, `${sessionId}.jsonl`), 'utf8');
    } catch {
      continue; // not this project dir
    }
    // Found the transcript (filenames are unique per session) — extract
    // whatever title lines it has and stop; no other dir can hold this file.
    return extractTitle(text);
  }
  return undefined;
}

function extractTitle(text: string): string | undefined {
  let aiTitle: string | undefined;
  let customTitle: string | undefined;
  for (const line of text.split('\n')) {
    if (!line) continue;
    let rec: unknown;
    try {
      rec = JSON.parse(line);
    } catch {
      continue;
    }
    if (!rec || typeof rec !== 'object') continue;
    const r = rec as Record<string, unknown>;
    if (r.type === 'ai-title' && typeof r.aiTitle === 'string') aiTitle = r.aiTitle;
    else if (r.type === 'custom-title' && typeof r.customTitle === 'string') customTitle = r.customTitle;
  }
  return customTitle ?? aiTitle;
}
