import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { lookupSessionTitle } from '../proxy/session-names.js';

function withProjectsDir(fn: (root: string) => void): void {
  const root = mkdtempSync(join(tmpdir(), 'session-names-test-'));
  try {
    fn(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

describe('lookupSessionTitle', () => {
  it('reads an ai-title line out of the transcript', () => {
    withProjectsDir((root) => {
      const projectDir = join(root, 'C--Users-x--claude');
      mkdirSync(projectDir);
      writeFileSync(
        join(projectDir, 'sess-1.jsonl'),
        '{"type":"ai-title","sessionId":"sess-1","aiTitle":"Fix the dashboard"}\n',
      );
      assert.equal(lookupSessionTitle('sess-1', root), 'Fix the dashboard');
    });
  });

  it('prefers a custom-title over an ai-title', () => {
    withProjectsDir((root) => {
      const projectDir = join(root, 'proj');
      mkdirSync(projectDir);
      writeFileSync(
        join(projectDir, 'sess-2.jsonl'),
        '{"type":"ai-title","sessionId":"sess-2","aiTitle":"Autogenerated"}\n' +
          '{"type":"custom-title","sessionId":"sess-2","customTitle":"My Name"}\n',
      );
      assert.equal(lookupSessionTitle('sess-2', root), 'My Name');
    });
  });

  it('returns undefined when the transcript has no title line at all', () => {
    withProjectsDir((root) => {
      const projectDir = join(root, 'proj');
      mkdirSync(projectDir);
      writeFileSync(join(projectDir, 'sess-3.jsonl'), '{"type":"mode","mode":"normal"}\n');
      assert.equal(lookupSessionTitle('sess-3', root), undefined);
    });
  });

  it('returns undefined, never throws, when the projects directory does not exist', () => {
    const missingRoot = join(tmpdir(), 'session-names-test-missing-' + Date.now());
    assert.doesNotThrow(() => lookupSessionTitle('anything', missingRoot));
    assert.equal(lookupSessionTitle('anything', missingRoot), undefined);
  });

  it('returns undefined when no project dir holds a matching transcript file', () => {
    withProjectsDir((root) => {
      mkdirSync(join(root, 'proj'));
      assert.equal(lookupSessionTitle('no-such-session', root), undefined);
    });
  });
});
